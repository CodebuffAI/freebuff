#!/usr/bin/env bun
/**
 * Regenerates `src/catalog.ts` — the model ids the gateway advertises for its
 * built-in providers.
 *
 * Sources:
 *   - https://models.dev/api.json      (the catalog opencode itself reads)
 *   - https://inference-api.nousresearch.com/v1/models  (Nous has no models.dev entry)
 *
 * Usage:
 *   bun scripts/sync-models.ts           # write src/catalog.ts
 *   bun scripts/sync-models.ts --check   # fail if the file is out of date
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const REPO_ROOT = resolve(import.meta.dir, '..')
const TARGET = join(REPO_ROOT, 'src', 'catalog.ts')

type Catalog = Record<string, string[]>

const MODELS_DEV_PROVIDERS: Record<string, string> = {
  openai: 'openai',
  openrouter: 'openrouter',
}

async function fromModelsDev(): Promise<Catalog> {
  const response = await fetch('https://models.dev/api.json')
  if (!response.ok) throw new Error(`models.dev answered ${response.status}`)
  const data = (await response.json()) as Record<string, { models?: Record<string, unknown> }>
  const catalog: Catalog = {}
  for (const [providerId, modelsDevId] of Object.entries(MODELS_DEV_PROVIDERS)) {
    const provider = data[modelsDevId]
    if (!provider?.models) continue
    catalog[providerId] = Object.keys(provider.models).sort()
  }
  return catalog
}

type NousModels = { data?: Array<{ id?: string }> }

async function fromNous(): Promise<string[]> {
  const response = await fetch('https://inference-api.nousresearch.com/v1/models')
  if (!response.ok) throw new Error(`Nous models endpoint answered ${response.status}`)
  const payload = (await response.json()) as NousModels
  return (payload.data ?? [])
    .map((entry) => entry.id)
    .filter((id): id is string => typeof id === 'string' && id.length > 0)
    .sort()
}

function render(catalog: Catalog): string {
  const lines = [
    '// Generated by `bun scripts/sync-models.ts` — do not edit by hand.',
    '// Sources: https://models.dev/api.json and the Nous inference API.',
    '',
    'export const CATALOG: Record<string, string[]> = {',
  ]
  for (const [provider, models] of Object.entries(catalog)) {
    lines.push(`  '${provider}': [`)
    for (const model of models) lines.push(`    '${model.replace(/'/g, "\\'")}',`)
    lines.push('  ],')
  }
  lines.push('}', '')
  return lines.join('\n')
}

async function main(): Promise<void> {
  const check = process.argv.includes('--check')
  const catalog: Catalog = { ...(await fromModelsDev()) }

  try {
    catalog['nous'] = await fromNous()
  } catch (error) {
    // Nous is optional: keep whatever is already committed if it is unreachable.
    console.warn(`! Nous catalog skipped: ${String(error)}`)
    const existing = readExisting()
    if (existing['nous']) catalog['nous'] = existing['nous']
  }

  const output = render(catalog)
  const counts = Object.entries(catalog)
    .map(([provider, models]) => `${provider}=${models.length}`)
    .join(' ')

  if (check) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : ''
    if (current !== output) {
      console.error('src/catalog.ts is out of date. Run `bun scripts/sync-models.ts`.')
      process.exit(1)
    }
    console.log(`catalog up to date (${counts})`)
    return
  }

  writeFileSync(TARGET, output)
  console.log(`wrote src/catalog.ts (${counts})`)
}

function readExisting(): Catalog {
  if (!existsSync(TARGET)) return {}
  const match = /export const CATALOG[^=]*=\s*(\{[\s\S]*\})/.exec(readFileSync(TARGET, 'utf8'))
  if (!match?.[1]) return {}
  try {
    return JSON.parse(match[1].replace(/'/g, '"').replace(/,\s*([}\]])/g, '$1')) as Catalog
  } catch {
    return {}
  }
}

await main()
